using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading;
using FastEnumUtility.Generators.Internals;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace FastEnumUtility.Generators;



/// <summary>
/// Provides code generation of IFastEnumBooster&lt;T&gt; implementation.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class FastEnumBoosterGenerator : IIncrementalGenerator
{
    #region IIncrementalGenerator
    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var typeDeclarations
            = context.SyntaxProvider.ForAttributeWithMetadataName
            (
                fullyQualifiedMetadataName: "FastEnumUtility.FastEnumAttribute`1",
                predicate: static (node, cancellationToken) =>
                {
                    cancellationToken.ThrowIfCancellationRequested();
                    return node
                        is ClassDeclarationSyntax
                        or StructDeclarationSyntax
                        or RecordDeclarationSyntax;
                },
                transform: static (context, cancellationToken) =>
                {
                    // note:
                    //  - The pipeline compares the value with the previous run, and skips the output step if it is equal.
                    //  - GeneratorAttributeSyntaxContext holds the semantic model, which is new for every compilation (= every keystroke in IDE).
                    //    Passing it as is made every booster look changed, so all of them were generated and parsed again on every edit.
                    //  - Only the strings needed for the output are extracted here, into records compared by value.
                    //    Symbols and syntax nodes are not kept either, so the old compilations are not held by the pipeline.

                    cancellationToken.ThrowIfCancellationRequested();
                    return BoosterModel.Create(new GenerateParameters(context), cancellationToken);
                }
            );

        context.RegisterSourceOutput(typeDeclarations, static (context, model) =>
        {
            if (model.Diagnostic is not null)
            {
                context.ReportDiagnostic(model.Diagnostic.ToDiagnostic());
                return;
            }

            var code = Generate(model);
            context.AddSource(model.FileName, code);
        });
    }
    #endregion


    #region Helpers
    private static DiagnosticModel? Diagnose(GenerateParameters param)
    {
        var containerType = param.ContainerType;
        var enumType = param.EnumType;

        //--- partial type only
        if (!containerType.IsPartial)
        {
            var descriptor = DiagnosticDescriptorProvider.MustBePartial;
            var location = containerType.SyntaxNode.Identifier.GetLocation();
            var args = containerType.TypeName;
            return DiagnosticModel.Create(descriptor, location, args);
        }

        //--- Disallow nested type
        if (containerType.IsNested)
        {
            var descriptor = DiagnosticDescriptorProvider.MustNotBeNested;
            var location = containerType.SyntaxNode.Identifier.GetLocation();
            var args = containerType.TypeName;
            return DiagnosticModel.Create(descriptor, location, args);
        }

        //--- Allow public or internal only
        if (!enumType.IsPublicOrInternal)
        {
            var descriptor = DiagnosticDescriptorProvider.MustBePublicOrInternal;
            var location = enumType.SyntaxNode.GetLocation();
            var args = enumType.SyntaxNode.GetText().ToString();
            return DiagnosticModel.Create(descriptor, location, args);
        }

        //--- Generic type argument must be enum type
        if (!enumType.IsEnum)
        {
            var descriptor = DiagnosticDescriptorProvider.MustBeEnumType;
            var location = enumType.SyntaxNode.GetLocation();
            var args = enumType.SyntaxNode.GetText().ToString();
            return DiagnosticModel.Create(descriptor, location, args);
        }

        return null;
    }


    private static string Generate(BoosterModel param)
    {
        var sb = new StringBuilder();
        emitHeader(sb);
        emitPragmaWarningDisable(sb, param);
        emitUsingDirectives(sb);
        emitNamespace(sb, param);
        emitBooster_Start(sb, param);
        emitGetName(sb, param);
        emitIsDefined_Enum(sb, param);
        emitIsDefined_String(sb, param);
        emitTryParseName(sb, param);
        emitBooster_End(sb);
        return sb.ToString();

        #region Local Functions
        static void emitHeader(StringBuilder sb)
        {
            sb.AppendLine("""
                // <auto-generated>
                // This .cs file is generated by FastEnum source generator.
                // </auto-generated>
                #nullable enable
                """);
        }


        static void emitPragmaWarningDisable(StringBuilder sb, BoosterModel param)
        {
            sb.AppendLine("""

                #pragma warning disable CS0612
                #pragma warning disable CS0618
                """);

            //--- supports [Obsolete(DiagnosticId = "xxx")]
            foreach (var x in param.EnumType.ObsoleteDiagnosticIds)
                sb.AppendLine($"#pragma warning disable {x}");
        }


        static void emitUsingDirectives(StringBuilder sb)
        {
            sb.AppendLine("""

                using System;
                using System.Globalization;
                using System.Runtime.CompilerServices;
                using FastEnumUtility;
                """);
        }


        static void emitNamespace(StringBuilder sb, BoosterModel param)
        {
            var container = param.ContainerType;
            if (container.IsGlobalNamespace)
                return;

            sb.AppendLine($"""

                namespace {container.Namespace};
                """);
        }


        static void emitBooster_Start(StringBuilder sb, BoosterModel param)
        {
            var container = param.ContainerType;
            var @enum = param.EnumType;
            sb.AppendLine($$"""

                partial {{container.TypeKind}} {{container.TypeName}} : IFastEnumBooster<{{@enum.TypeName}}>
                {
                    #region IFastEnumBooster<T>
                """);
        }


        static void emitGetName(StringBuilder sb, BoosterModel param)
        {
            var @enum = param.EnumType;
            sb.AppendLine($$"""
                    /// <inheritdoc/>
                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    static string? IFastEnumBooster<{{@enum.TypeName}}>.GetName({{@enum.TypeName}} value)
                    {
                        return value switch
                        {
                """);
            foreach (var field in @enum.DistinctedFields)
            {
                sb.AppendLine($"            {@enum.TypeName}.{field.Name} => nameof({@enum.TypeName}.{field.Name}),");
            }
            sb.AppendLine($$"""
                            _ => null,
                        };
                    }
                """);
        }


        static void emitIsDefined_Enum(StringBuilder sb, BoosterModel param)
        {
            var @enum = param.EnumType;
            sb.AppendLine($$"""

                    /// <inheritdoc/>
                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    static bool IFastEnumBooster<{{@enum.TypeName}}>.IsDefined({{@enum.TypeName}} value)
                    {
                        return value switch
                        {
                """);
            foreach (var field in @enum.DistinctedFields)
            {
                sb.AppendLine($"            {@enum.TypeName}.{field.Name} => true,");
            }
            sb.AppendLine($$"""
                            _ => false,
                        };
                    }
                """);
        }


        static void emitIsDefined_String(StringBuilder sb, BoosterModel param)
        {
            var @enum = param.EnumType;
            sb.AppendLine($$"""

                    /// <inheritdoc/>
                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    static bool IFastEnumBooster<{{@enum.TypeName}}>.IsDefined(ReadOnlySpan<char> name)
                    {
                        return name switch
                        {
                """);
            foreach (var field in @enum.Fields)
            {
                sb.AppendLine($"            nameof({@enum.TypeName}.{field.Name}) => true,");
            }
            sb.AppendLine("""
                            _ => false,
                        };
                    }
                """);
        }


        static void emitTryParseName(StringBuilder sb, BoosterModel param)
        {
            var @enum = param.EnumType;
            sb.AppendLine($$"""

                    /// <inheritdoc/>
                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    static bool IFastEnumBooster<{{@enum.TypeName}}>.TryParseName(ReadOnlySpan<char> text, bool ignoreCase, out {{@enum.TypeName}} result)
                    {
                        return ignoreCase
                            ? caseInsensitive(text, out result)
                            : caseSensitive(text, out result);

                        #region Local Functions
                        [MethodImpl(MethodImplOptions.AggressiveInlining)]
                        static bool caseSensitive(ReadOnlySpan<char> text, out {{@enum.TypeName}} result)
                        {
                            switch (text)
                            {
                """);
            foreach (var field in @enum.Fields)
            {
                sb.AppendLine($$"""
                                    case nameof({{@enum.TypeName}}.{{field.Name}}):
                                        result = {{@enum.TypeName}}.{{field.Name}};
                                        return true;

                    """);
            }
            sb.AppendLine($$"""
                                default:
                                    result = default;
                                    return false;
                            }
                        }

                        [MethodImpl(MethodImplOptions.AggressiveInlining)]
                        static bool caseInsensitive(ReadOnlySpan<char> text, out {{@enum.TypeName}} result)
                        {
                            switch (text.Length)
                            {
                """);
            var byNameLength
                = @enum.Fields
                .GroupBy(static x => x.Name.Length)
                .OrderBy(static x => x.Key);
            foreach (var group in byNameLength)
            {
                sb.AppendLine($"                case {group.Key}:");
                foreach (var field in group)
                {
                    sb.AppendLine($$"""
                                            if (text.Equals(nameof({{@enum.TypeName}}.{{field.Name}}), StringComparison.OrdinalIgnoreCase))
                                            {
                                                result = {{@enum.TypeName}}.{{field.Name}};
                                                return true;
                                            }
                        """);
                }
                sb.AppendLine("""
                                        break;

                    """);
            }
            sb.AppendLine("""
                                default:
                                    break;
                            }

                            result = default;
                            return false;
                        }
                        #endregion
                    }
                """);
        }


        static void emitBooster_End(StringBuilder sb)
        {
            sb.AppendLine("""
                    #endregion
                }
                """);
        }
        #endregion
    }
    #endregion


    #region Nested Types
    /// <summary>
    /// Everything the output step needs, compared by value.
    /// </summary>
    private sealed record BoosterModel(string FileName, DiagnosticModel? Diagnostic, ContainerModel ContainerType, EnumModel EnumType)
    {
        public static BoosterModel Create(GenerateParameters param, CancellationToken cancellationToken)
        {
            var container = param.ContainerType;
            var containerModel = new ContainerModel(container.IsGlobalNamespace, container.Namespace, container.TypeKind, container.TypeName);
            var diagnostic = Diagnose(param);
            if (diagnostic is not null)
                return new(param.FileName, diagnostic, containerModel, new(param.EnumType.TypeName, new([]), new([]), new([])));

            cancellationToken.ThrowIfCancellationRequested();
            var @enum = param.EnumType;
            var enumModel = new EnumModel(
                @enum.TypeName,
                new(@enum.Fields.Select(static x => new FieldModel(x.Name)).ToArray()),
                new(@enum.DistinctedFields.Select(static x => new FieldModel(x.Name)).ToArray()),
                new(getObsoleteDiagnosticIds(@enum)));
            return new(param.FileName, null, containerModel, enumModel);


            #region Local Functions
            static string[] getObsoleteDiagnosticIds(EnumTypeMetadata @enum)
            {
                //--- supports [Obsolete(DiagnosticId = "xxx")]
                IEnumerable<ISymbol> types = [@enum.TypeSymbol];
                IEnumerable<ISymbol> fields = @enum.Fields;
                return types
                    .Concat(fields)
                    .SelectMany(static x => x.GetAttributes())
                    .Where(static x =>
                    {
                        var @class = x.AttributeClass;
                        return (@class?.ContainingNamespace.MetadataName == typeof(ObsoleteAttribute).Namespace)
                            && (@class?.MetadataName is nameof(ObsoleteAttribute));
                    })
                    .SelectMany(static x => x.NamedArguments)
                    .Where(static x => x.Key is "DiagnosticId")
                    .Select(static x => x.Value)
                    .Where(static x => x.Type?.SpecialType is SpecialType.System_String)
                    .Select(static x => (string?)x.Value)
                    .Select(static x => x?.Trim())
                    .Where(static x => !string.IsNullOrWhiteSpace(x))
                    .Distinct()
                    .OrderBy(static x => x)
                    .ToArray()!;
            }
            #endregion
        }
    }


    private sealed record ContainerModel(bool IsGlobalNamespace, string Namespace, string TypeKind, string TypeName);


    private sealed record EnumModel(string TypeName, EquatableArray<FieldModel> Fields, EquatableArray<FieldModel> DistinctedFields, EquatableArray<string> ObsoleteDiagnosticIds);


    private sealed record FieldModel(string Name);


    /// <summary>
    /// A diagnostic, compared by value.
    /// </summary>
    /// <remarks>
    /// The <see cref="Location"/> is kept as is. A location in source equals another one with the same syntax tree and span,
    /// and the syntax tree of a file stays the same object until the file is edited, so the model still equals the previous one.
    /// A location created again from the file path would not be in source, and the compiler would ignore
    /// #pragma warning disable and .editorconfig for the diagnostic.
    /// </remarks>
    private sealed record DiagnosticModel(string Id, Location Location, string Argument)
    {
        public static DiagnosticModel Create(DiagnosticDescriptor descriptor, Location location, string argument)
            => new(descriptor.Id, location, argument);


        public Diagnostic ToDiagnostic()
        {
            var descriptor = this.Id switch
            {
                "FE0001" => DiagnosticDescriptorProvider.MustBePartial,
                "FE0002" => DiagnosticDescriptorProvider.MustNotBeNested,
                "FE0003" => DiagnosticDescriptorProvider.MustBePublicOrInternal,
                _ => DiagnosticDescriptorProvider.MustBeEnumType,
            };
            return Diagnostic.Create(descriptor, this.Location, this.Argument);
        }
    }


    private sealed class GenerateParameters
    {
        #region Properties
        public string FileName { get; }
        public ContainerTypeMetadata ContainerType { get; }
        public EnumTypeMetadata EnumType { get; }
        #endregion


        #region Constructors
        public GenerateParameters(GeneratorAttributeSyntaxContext context)
        {
            var containerNode = (TypeDeclarationSyntax)context.TargetNode;
            var containerSymbol = (INamedTypeSymbol)context.TargetSymbol;
            var enumNode = getEnumNode(containerNode);
            var enumSymbol = getEnumSymbol(context);

            this.FileName = createFileName(containerSymbol);
            this.ContainerType = new(containerNode, containerSymbol);
            this.EnumType = new(enumNode, enumSymbol);


            #region Local Functions
            static string createFileName(ISymbol symbol)
            {
                var typeName = symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                var escaped = typeName.Replace("global::", "").Replace("<", "_").Replace(">", "_");
                return $"{escaped}.FastEnumBooster.g.cs";
            }


            static TypeSyntax getEnumNode(MemberDeclarationSyntax syntax)
            {
                var attributes = syntax.AttributeLists.SelectMany(static x => x.Attributes);
                foreach (var attr in attributes)
                {
                    var generic = getGenericNameSyntax(attr.Name);
                    if (generic is null)
                        continue;

                    if (generic.Identifier.Text is not ("FastEnum" or "FastEnumAttribute"))
                        continue;

                    var @enum = generic.TypeArgumentList.Arguments.First();
                    return @enum;
                }
                throw new InvalidOperationException("FastEnumAttribute<T> is not annotated.");
            }


            static GenericNameSyntax? getGenericNameSyntax(NameSyntax syntax)
            {
                if (syntax is QualifiedNameSyntax qualified)  // [global::FastEnumUtility.FastEnum<TEnum>]
                    return getGenericNameSyntax(qualified.Right);

                if (syntax is GenericNameSyntax generic)  // [FastEnum<TEnum>]
                    return generic;

                return null;
            }


            static INamedTypeSymbol getEnumSymbol(GeneratorAttributeSyntaxContext context)
            {
                var attr = context.Attributes.First(static x => x.AttributeClass!.MetadataName is "FastEnumAttribute`1");
                return (INamedTypeSymbol)attr.AttributeClass!.TypeArguments[0];
            }
            #endregion
        }
        #endregion
    }



    private sealed class ContainerTypeMetadata
    {
        #region Properties
        public TypeDeclarationSyntax SyntaxNode { get; }
        public INamedTypeSymbol TypeSymbol { get; }
        public bool IsGlobalNamespace { get; }
        public bool IsGeneric { get; }
        public bool IsPartial { get; }
        public bool IsNested { get; }
        public string Namespace { get; }
        public string TypeKind { get; }
        public string TypeName { get; }
        #endregion


        #region Constructors
        public ContainerTypeMetadata(TypeDeclarationSyntax syntax, INamedTypeSymbol symbol)
        {
            this.SyntaxNode = syntax;
            this.TypeSymbol = symbol;
            this.IsGlobalNamespace = symbol.ContainingNamespace.IsGlobalNamespace;
            this.IsGeneric = symbol.IsGenericType;
            this.IsPartial = syntax.Modifiers.Any(static x => x.IsKind(SyntaxKind.PartialKeyword));
            this.IsNested = syntax.Parent is TypeDeclarationSyntax;
            this.Namespace = symbol.ContainingNamespace.ToDisplayString();
            this.TypeKind = toTypeKind(symbol);
            this.TypeName = symbol.Name;


            #region Local Functions
            static string toTypeKind(INamedTypeSymbol symbol)
            {
                return (symbol.IsRecord, symbol.IsValueType) switch
                {
                    (true, true) => "record struct",
                    (true, false) => "record class",
                    (false, true) => "struct",
                    (false, false) => "class",
                };
            }
            #endregion
        }
        #endregion
    }



    private sealed class EnumTypeMetadata
    {
        #region Properties
        public TypeSyntax SyntaxNode { get; }
        public INamedTypeSymbol TypeSymbol { get; }
        public bool IsPublicOrInternal { get; }
        public bool IsEnum { get; }
        public string TypeName { get; }
        public string UnderlyingType { get; }
        public IReadOnlyList<IFieldSymbol> Fields { get; }
        public IReadOnlyList<IFieldSymbol> DistinctedFields { get; }
        #endregion


        #region Constructors
        public EnumTypeMetadata(TypeSyntax syntax, INamedTypeSymbol symbol)
        {
            this.SyntaxNode = syntax;
            this.TypeSymbol = symbol;
            this.IsPublicOrInternal = isPublicOrInternal(symbol);
            this.IsEnum = symbol.TypeKind is TypeKind.Enum;
            this.TypeName = symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            this.UnderlyingType = symbol.EnumUnderlyingType?.ToDisplayString() ?? "int";
            this.Fields = symbol.GetMembers().OfType<IFieldSymbol>().ToArray();
#pragma warning disable RS1024  // Use 'SymbolEqualityComparer' when comparing symbols
            // note:
            //  - In this case, where a custom IEqualityComparer<T> is being utilized, the RS1024 warning is deemed inappropriate and is recognized as a bug in Microsoft.CodeAnalysis.CSharp.
            //  - Although this issue has been rectified in version 4.6.0, the use of version 4.4.0 does not present any functional problems.
            //  - Consequently, we have opted to address this by suppressing the warning.
            this.DistinctedFields = this.Fields.Distinct(new FieldSymbolComparer()).ToArray();
#pragma warning restore RS1024


            #region Local Functions
            static bool isPublicOrInternal(INamedTypeSymbol symbol)
            {
                // note:
                //  - For file-local types, accessibility is set to 'Friend' (= Internal).
                //  - Therefore, it is necessary to determine separately that it is a file-local types.

                if (symbol.IsFileLocal)
                    return false;

                return symbol.DeclaredAccessibility
                    is Accessibility.Public
                    or Accessibility.Internal;
            }
            #endregion
        }
        #endregion


        #region Nested Types
        private sealed class FieldSymbolComparer : IEqualityComparer<IFieldSymbol>
        {
            /// <inheritdoc/>
            public bool Equals(IFieldSymbol x, IFieldSymbol y)
                => EqualityComparer<object>.Default.Equals(x.ConstantValue!, y.ConstantValue!);


            /// <inheritdoc/>
            public int GetHashCode(IFieldSymbol obj)
                => EqualityComparer<object>.Default.GetHashCode(obj.ConstantValue!);
        }
        #endregion
    }
    #endregion
}
